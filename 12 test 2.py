'''Write a program that:

Keeps asking the user for a number.
If the user enters:
a negative number → stop the loop.
a multiple of 5 → skip it (don't add it to the total).
any other positive number → add it to the total.
After the loop ends, print:
Total sum
Count of numbers that were added'''

total = 0
count = 0
for i in range(1,100):
    num = int(input("Enter number: "))
    if num <0:
        break
    if num %5 == 0:
        continue
    if num >=0:
        total += num
        count += 1
print(total)
print(count)

